#!/usr/bin/env python3
"""Embed llama/sprig-llama into sprig.el as `sprig--llama-source-text'.

The client layer is a script, not a .el file, and package managers such as
straight ship only .el files, so a llama/ dir beside the loaded library is not
there to read.  sprig.el therefore carries the script's bytes in a defconst,
regenerated by this script whenever the client changes.  A test guards that the
two match.  The broker is embedded the same way, for the same reason.

Run from anywhere:  python3 llama/embed.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CLIENT = os.path.join(HERE, "sprig-llama")
SPRIG = os.path.join(HERE, os.pardir, "sprig.el")
BEGIN = ";;;; llama-source-begin (generated by llama/embed.py; do not edit by hand)"
END = ";;;; llama-source-end"


def elisp_string(text):
    # Only backslash and double-quote need escaping in an Elisp string literal;
    # newlines stay literal so the diff is legible.
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    with open(CLIENT, "r", encoding="utf-8") as f:
        source = f.read()
    block = (
        BEGIN + "\n"
        "(defconst sprig--llama-source-text\n"
        + elisp_string(source) + "\n"
        '  "Embedded copy of llama/sprig-llama, installed on first use.\n'
        "Generated by llama/embed.py; the test\n"
        "`sprig-test-llama-source-matches-file' guards that it matches the\n"
        'script.  Regenerate with llama/embed.py after editing the client.")\n'
        + END
    )
    with open(SPRIG, "r", encoding="utf-8") as f:
        sprig = f.read()
    i = sprig.index(BEGIN)
    j = sprig.index(END) + len(END)
    sprig = sprig[:i] + block + sprig[j:]
    with open(SPRIG, "w", encoding="utf-8") as f:
        f.write(sprig)
    print(f"embedded {len(source)} bytes into sprig.el")


if __name__ == "__main__":
    main()
